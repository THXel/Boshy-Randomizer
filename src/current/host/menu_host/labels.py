def text(key, language):
    return ROWS[key][LANGUAGES.index(language)]


def stage(name, language):
    # Original proper names stay intact; existing translated suffixes are reused.
    catalogue = json.loads((REPO / "assets/locales" / (language + ".json")).read_text())
    english = json.loads((REPO / "assets/locales/en.json").read_text())
    return catalogue.get(name, english.get(name, name))
